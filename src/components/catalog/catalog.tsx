import { router, type Href } from 'expo-router';
import { StatusBar } from 'expo-status-bar';
import { Image, Pressable, ScrollView, Text, useWindowDimensions, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { groups, shots, type Shot } from './shots';

/**
 * The catalog: every showcase in the repo, as a wall of thumbnails.
 *
 * This is **repo chrome, not a showcase**. It lives in `src/components/` rather
 * than `src/features/<slug>/`, so `lock` and `preflight` do not track it and
 * `showcase.js wipe` does not take it with the screens.
 *
 * `src/app/index.tsx` is a derived file — `showcase.js use`, `rm`, `wipe` and
 * `record.js` all rewrite it as a boot redirect, which is right for a take:
 * the device should open straight on the screen being filmed. Afterwards
 * `node tools/showcase.js catalog` points it back here.
 *
 * The thumbnails are generated by `python tools/catalog.py` and go stale the
 * moment a screen changes, so re-run it after a layout pass.
 *
 * The grid is sized from `useWindowDimensions()` (I2), because this one is
 * genuinely looked at on a desktop browser as often as at phone width.
 */

const FG = '#15181C';
const SUB = '#6B7480';
const PAGE = '#F4F5F7';
const CARD = '#FFFFFF';
const EDGE = '#E4E7EB';

function Thumb({ shot, width }: { shot: Shot; width: number }) {
  const height = Math.round((width * 852) / 393);

  return (
    <Pressable
      onPress={() => router.push(shot.route as Href)}
      accessibilityRole="link"
      accessibilityLabel={`Open ${shot.slug}`}
      style={{ width }}
    >
      {({ pressed }) => (
        <View style={{ width, opacity: pressed ? 0.75 : 1 }}>
          <View
            style={{
              width,
              height,
              borderRadius: 10,
              overflow: 'hidden',
              backgroundColor: CARD,
              borderWidth: 1,
              borderColor: EDGE,
            }}
          >
            {/* An Image needs a numeric size: absolute insets alone make it
                paint nothing on native, silently (RULES Part 7). */}
            <Image source={shot.thumb} style={{ width, height }} resizeMode="cover" />
          </View>

          <Text
            numberOfLines={1}
            style={{
              marginTop: 6,
              fontFamily: 'PlusJakartaSans_600SemiBold',
              fontSize: 11,
              lineHeight: 15,
              color: FG,
            }}
          >
            {shot.slug}
          </Text>
        </View>
      )}
    </Pressable>
  );
}

export function Catalog() {
  const { width } = useWindowDimensions();
  const insets = useSafeAreaInsets();

  const margin = 20;
  const gutter = 12;
  /**
   * As many ~104dp columns as fit, between three and eight.
   *
   * Three at phone width and six or more on a laptop. At a 140dp target this
   * came out two across on a phone, which turned 35 screens into a very long
   * scroll — a catalog is for seeing them together, so density wins here in a
   * way it would not on a real screen.
   */
  const cols = Math.max(3, Math.min(8, Math.floor((width - margin * 2 + gutter) / (104 + gutter))));
  const col = (width - margin * 2 - gutter * (cols - 1)) / cols;

  const apps = groups();

  return (
    <View style={{ flex: 1, backgroundColor: PAGE }}>
      <StatusBar style="dark" />

      <ScrollView
        showsVerticalScrollIndicator={false}
        contentContainerStyle={{
          paddingTop: (insets.top || 24) + 12,
          paddingBottom: (insets.bottom || 24) + 32,
        }}
      >
        <View style={{ marginHorizontal: margin, marginBottom: 20 }}>
          <Text
            style={{
              fontFamily: 'PlusJakartaSans_800ExtraBold',
              fontSize: 26,
              lineHeight: 33,
              color: FG,
            }}
          >
            showoff
          </Text>
          <Text
            style={{
              fontFamily: 'PlusJakartaSans_400Regular',
              fontSize: 13,
              lineHeight: 18,
              color: SUB,
            }}
          >
            {`${shots.length} screens across ${apps.length} apps — tap one to open it`}
          </Text>
        </View>

        {apps.map((app) => {
          const rows: Shot[][] = [];
          const mine = shots.filter((s) => s.group === app);
          for (let i = 0; i < mine.length; i += cols) rows.push(mine.slice(i, i + cols));

          return (
            <View key={app} style={{ marginBottom: 26 }}>
              <View
                style={{
                  marginHorizontal: margin,
                  marginBottom: 10,
                  flexDirection: 'row',
                  alignItems: 'baseline',
                  gap: 8,
                }}
              >
                <Text
                  style={{
                    fontFamily: 'PlusJakartaSans_700Bold',
                    fontSize: 15,
                    lineHeight: 20,
                    color: FG,
                    textTransform: 'capitalize',
                  }}
                >
                  {app}
                </Text>
                <Text
                  style={{
                    fontFamily: 'PlusJakartaSans_400Regular',
                    fontSize: 11.5,
                    lineHeight: 20,
                    color: SUB,
                  }}
                >
                  {`${mine.length} ${mine.length === 1 ? 'screen' : 'screens'}`}
                </Text>
              </View>

              {rows.map((row) => (
                <View
                  key={row[0].slug}
                  style={{
                    marginHorizontal: margin,
                    marginBottom: gutter,
                    flexDirection: 'row',
                    gap: gutter,
                  }}
                >
                  {row.map((s) => (
                    <Thumb key={s.slug} shot={s} width={col} />
                  ))}
                </View>
              ))}
            </View>
          );
        })}
      </ScrollView>
    </View>
  );
}
